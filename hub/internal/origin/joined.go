package origin

import (
	"regexp"
	"strings"

	"github.com/USA-RedDragon/talaria/hub/internal/hub"
	"github.com/USA-RedDragon/talaria/hub/internal/notice"
)

// Hermes joins consecutive user-role rows into one row (the model API needs
// the roles to alternate), so a message the user typed can carry text that
// another writer put in the chat after it: an agent message, a subagent
// result, a background process notice. Each of those opens with a header at
// the start of a line after a blank line. Split cuts such a row at those
// headers, so the user's bubble holds only what the user typed and each block
// shows as its own card.
var (
	blockOpen = regexp.MustCompile(`(?m)^(?:` +
		`\[Agent message am_[0-9a-f]{16} from [^\]\n]{1,400}\]\n|` +
		`\[ASYNC DELEGATION (?:COMPLETE|BATCH COMPLETE|TASK FAILED) \x{2014} |` +
		`\[IMPORTANT: Background process |` +
		`\[Background process |` +
		`\[IMPORTANT: \d+ background processes completed\. )`)
	// blockFooter ends a block the gateway wrote: what follows is the next
	// row's text.
	blockFooter = regexp.MustCompile(`(?m)^\[INTERNAL NOTIFICATION \x{2014} generated by the Hermes gateway[^\n]*\][ \t]*$`)
)

// Split cuts text into what the user typed and the injected blocks that were
// joined to it. typed is the text outside the blocks (before the first and
// after a block that has a closing footer). blocks is empty when text has no
// block, and then typed is text as it came.
func Split(text string) (typed string, blocks []string) {
	locs := blockOpen.FindAllStringIndex(text, -1)
	var starts []int
	for _, l := range locs {
		if l[0] == 0 || strings.HasSuffix(text[:l[0]], "\n\n") {
			starts = append(starts, l[0])
		}
	}
	if len(starts) == 0 {
		return text, nil
	}
	parts := []string{text[:starts[0]]}
	for i, s := range starts {
		end := len(text)
		if i+1 < len(starts) {
			end = starts[i+1]
		}
		seg := text[s:end]
		if f := blockFooter.FindStringIndex(seg); f != nil {
			parts = append(parts, seg[f[1]:])
			seg = seg[:f[1]]
		}
		if notice.Parse(hub.CutInjectedNotes(seg)) == nil {
			// Not a block it knows: it stays in the text.
			parts = append(parts, seg)
			continue
		}
		blocks = append(blocks, strings.TrimSpace(seg))
	}
	if len(blocks) == 0 {
		return text, nil
	}
	var kept []string
	for _, p := range parts {
		if p = strings.TrimSpace(p); p != "" {
			kept = append(kept, p)
		}
	}
	return strings.Join(kept, "\n\n"), blocks
}

// joined is the view of a row that carries injected blocks: the user's
// bubble (none when they typed nothing) and a card for each block, in
// View.After. ok is false for a row with no block.
func joined(text, why string) (View, bool) {
	typedText, blocks := Split(hub.CutInjectedNotes(text))
	if len(blocks) == 0 {
		return View{}, false
	}
	var cards []*notice.Notice
	for _, b := range blocks {
		cards = append(cards, parse(b))
	}
	if strings.TrimSpace(typedText) == "" {
		return View{Show: ShowCard, Notice: cards[0], After: cards[1:], Why: why}, true
	}
	return View{Show: ShowUser, Text: typedText, After: cards, Why: why}, true
}
